import 'package:flutter_bloc/flutter_bloc.dart';
import 'dart:developer' as developer;
import 'package:uuid/uuid.dart';

import '../../../../features/documents/domain/models/analysis_model.dart'
    as doc_models;
import '../../../../features/documents/domain/repositories/document_repository.dart';
import '../../domain/models/checklist_model.dart';
import '../../domain/repositories/checklist_repository.dart';
import 'checklist_state.dart';

/// ChecklistCubit manages checklist state with optimistic updates
class ChecklistCubit extends Cubit<ChecklistState> {
  final ChecklistRepository _checklistRepository;
  final DocumentRepository _documentRepository;

  // Store the current documentId for mutations
  String? _currentDocumentId;

  // Cached items for optimistic updates
  List<ChecklistItemModel> _cachedItems = [];

  // Track if we've already auto-generated for this document to prevent loops
  final Set<String> _autoGeneratedDocuments = {};

  ChecklistCubit(this._checklistRepository, this._documentRepository)
      : super(const ChecklistInitial());

  /// Load checklist for document
  /// Auto-generates from document analysis if checklist is empty (idempotent)
  Future<void> loadChecklist(String documentId) async {
    developer.log('[ChecklistCubit] loadChecklist called', name: 'ChecklistCubit', error: {'documentId': documentId});
    _currentDocumentId = documentId;
    emit(const ChecklistLoading());

    final result = await _checklistRepository.getChecklist(documentId);

    await result.fold(
      (failure) async {
        developer.log('[ChecklistCubit] getChecklist failed', name: 'ChecklistCubit', error: failure);
        emit(ChecklistError(failure.message, code: failure.code));
      },
      (items) async {
        developer.log('[ChecklistCubit] getChecklist success', name: 'ChecklistCubit', error: {'itemCount': items.length, 'documentId': documentId});
        _cachedItems = List.unmodifiable(items);
        emit(ChecklistLoaded(List.unmodifiable(items)));

        // Auto-generate from analysis if checklist is empty and not already done
        if (items.isEmpty && !_autoGeneratedDocuments.contains(documentId)) {
          developer.log('[ChecklistCubit] Checklist empty, auto-generating from analysis', name: 'ChecklistCubit', error: {'documentId': documentId});
          await _autoGenerateFromAnalysis(documentId);
        } else if (items.isNotEmpty) {
          developer.log('[ChecklistCubit] Checklist already has items, skipping auto-generation', name: 'ChecklistCubit', error: {'itemCount': items.length, 'documentId': documentId});
        } else {
          developer.log('[ChecklistCubit] Already auto-generated for this document, skipping', name: 'ChecklistCubit', error: {'documentId': documentId});
        }
      },
    );
  }

  /// Auto-generate checklist items from document analysis
  /// Converts AnalysisModel.checklistItems (from analysis_model.dart) to ChecklistItemModel (from checklist_model.dart)
  Future<void> _autoGenerateFromAnalysis(String documentId) async {
    developer.log('[ChecklistCubit] _autoGenerateFromAnalysis started', name: 'ChecklistCubit', error: {'documentId': documentId});
    try {
      final analysisResult = await _documentRepository.getAnalysis(documentId);

      await analysisResult.fold(
        (failure) async {
          developer.log('[ChecklistCubit] getAnalysis failed', name: 'ChecklistCubit', error: {'documentId': documentId, 'failure': failure.toString()});
          // Analysis not found or error - just keep empty checklist
          // Don't emit error, user can manually add tasks
        },
        (analysis) async {
          if (analysis == null || analysis.checklistItems.isEmpty) {
            developer.log('[ChecklistCubit] No analysis or no checklist items in analysis', name: 'ChecklistCubit', error: {'documentId': documentId, 'analysisNull': analysis == null, 'checklistItemsEmpty': analysis?.checklistItems.isEmpty ?? true});
            // No analysis or no checklist items in analysis
            return;
          }

          developer.log('[ChecklistCubit] getAnalysis success, found items', name: 'ChecklistCubit', error: {'documentId': documentId, 'analysisItemCount': analysis.checklistItems.length});

          // Convert doc_models.ChecklistItemModel to checklist_models.ChecklistItemModel
          final generatedItems = analysis.checklistItems.map(_convertAnalysisItem).toList();

          if (generatedItems.isEmpty) {
            developer.log('[ChecklistCubit] Generated items list is empty after conversion', name: 'ChecklistCubit', error: {'documentId': documentId});
            return;
          }

          developer.log('[ChecklistCubit] Generated items from analysis', name: 'ChecklistCubit', error: {'documentId': documentId, 'generatedItemCount': generatedItems.length});

          // Mark as auto-generated to prevent re-generation loops
          _autoGeneratedDocuments.add(documentId);

          // Save generated items to Supabase
          final saveResult = await _checklistRepository.saveChecklist(documentId, generatedItems);

          saveResult.fold(
            (failure) {
              developer.log('[ChecklistCubit] saveChecklist FAILED', name: 'ChecklistCubit', error: {'documentId': documentId, 'failure': failure.toString(), 'failureCode': failure.code, 'failureMessage': failure.message});
              // Failed to save - remove from auto-generated set so it can retry
              _autoGeneratedDocuments.remove(documentId);
              // Surface the error to user via errorMessage in state (for SnackBar display)
              emit(ChecklistLoaded(
                List.unmodifiable(_cachedItems),
                errorMessage: 'Failed to auto-generate checklist: ${failure.message}',
              ));
            },
            (savedItems) {
              developer.log('[ChecklistCubit] saveChecklist SUCCESS', name: 'ChecklistCubit', error: {'documentId': documentId, 'savedItemCount': savedItems.length});
              _cachedItems = List.unmodifiable(savedItems);
              emit(ChecklistLoaded(List.unmodifiable(savedItems)));
            },
          );
        },
      );
    } catch (e, stackTrace) {
      developer.log('[ChecklistCubit] _autoGenerateFromAnalysis exception', name: 'ChecklistCubit', error: {'documentId': documentId, 'error': e.toString(), 'stackTrace': stackTrace.toString()});
      // Swallow errors in auto-generation - user can manually add tasks
      _autoGeneratedDocuments.remove(documentId);
    }
  }

  /// Convert analysis model checklist item to checklist model item
  ChecklistItemModel _convertAnalysisItem(doc_models.ChecklistItemModel item) {
    // Convert ChecklistCategory from analysis_model to checklist_model
    final category = _convertCategory(item.category);

    // Generate a valid UUID v4 for the database ID.
    // The AI analysis returns non-UUID string IDs like "check_1", "check_2".
    // We MUST NOT pass those to Supabase as the `id` column is type uuid.
    // We also don't store the AI ID anywhere since it's not needed after conversion.
    final validId = const Uuid().v4();

    return ChecklistItemModel(
      id: validId,
      title: item.title,
      description: item.description,
      isCompleted: item.isCompleted,
      category: category,
      priority: item.priority,
      dueDate: item.dueDate,
      completedAt: item.isCompleted ? DateTime.now() : null,
      pageNumber: null,
      relatedClauseId: null,
    );
  }

  /// Convert ChecklistCategory from analysis_model to checklist_model
  ChecklistCategory _convertCategory(doc_models.ChecklistCategory category) {
    return ChecklistCategory.values.firstWhere(
      (e) => e.name == category.name,
      orElse: () => ChecklistCategory.other,
    );
  }

  /// Watch checklist for real-time updates
  Stream<List<ChecklistItemModel>> watchChecklist(String documentId) {
    _currentDocumentId = documentId;
    return _checklistRepository.watchChecklist(documentId);
  }

  /// Toggle checklist item completion (optimistic update)
  Future<void> toggleItem(ChecklistItemModel item) async {
    if (_currentDocumentId == null) {
      emit(const ChecklistError('No document loaded', code: 'no_document'));
      return;
    }

    // Store previous state for rollback on failure
    final previousItems = List<ChecklistItemModel>.from(_cachedItems);

    // Optimistic update: immediately update local state
    final updatedItem = item.copyWith(
      isCompleted: !item.isCompleted,
      completedAt: !item.isCompleted ? DateTime.now() : null,
    );

    _cachedItems = _cachedItems
        .map((i) => i.id == item.id ? updatedItem : i)
        .toList();

    // Emit updated list immediately (no loading state)
    emit(ChecklistLoaded(List.unmodifiable(_cachedItems)));

    // Background sync to server
    final result = await _checklistRepository.updateChecklistItem(
      _currentDocumentId!,
      updatedItem,
    );

    result.fold(
      (failure) {
        // Rollback on failure - keep list visible, show error via errorMessage
        _cachedItems = previousItems;
        emit(ChecklistLoaded(
          List.unmodifiable(_cachedItems),
          errorMessage: failure.message,
        ));
      },
      (synced) {
        // Ensure local state matches server (in case of any differences)
        _cachedItems = _cachedItems
            .map((i) => i.id == synced.id ? synced : i)
            .toList();
        emit(ChecklistLoaded(List.unmodifiable(_cachedItems)));
      },
    );
  }

  /// Update checklist item (optimistic update)
  Future<void> updateItem(ChecklistItemModel item) async {
    if (_currentDocumentId == null) {
      emit(const ChecklistError('No document loaded', code: 'no_document'));
      return;
    }

    // Store previous state for rollback on failure
    final previousItems = List<ChecklistItemModel>.from(_cachedItems);

    // Optimistic update
    _cachedItems = _cachedItems
        .map((i) => i.id == item.id ? item : i)
        .toList();

    emit(ChecklistLoaded(List.unmodifiable(_cachedItems)));

    // Background sync to server
    final result = await _checklistRepository.updateChecklistItem(
      _currentDocumentId!,
      item,
    );

    result.fold(
      (failure) {
        _cachedItems = previousItems;
        emit(ChecklistLoaded(
          List.unmodifiable(_cachedItems),
          errorMessage: failure.message,
        ));
      },
      (synced) {
        _cachedItems = _cachedItems
            .map((i) => i.id == synced.id ? synced : i)
            .toList();
        emit(ChecklistLoaded(List.unmodifiable(_cachedItems)));
      },
    );
  }

  /// Add new checklist item (optimistic update)
  /// Ensures the item has a valid UUID v4 before sending to Supabase.
  Future<void> addItem(ChecklistItemModel item) async {
    if (_currentDocumentId == null) {
      emit(const ChecklistError('No document loaded', code: 'no_document'));
      return;
    }

    // Defensive: ensure item has a valid UUID v4.
    // If the caller passed an invalid ID (e.g., from AI analysis), replace it.
    final validItem = _ensureValidUuid(item);

    final previousItems = List<ChecklistItemModel>.from(_cachedItems);

    _cachedItems = [..._cachedItems, validItem];
    emit(ChecklistLoaded(List.unmodifiable(_cachedItems)));

    final result = await _checklistRepository.addChecklistItem(
      _currentDocumentId!,
      validItem,
    );

    result.fold(
      (failure) {
        _cachedItems = previousItems;
        emit(ChecklistLoaded(
          List.unmodifiable(_cachedItems),
          errorMessage: failure.message,
        ));
      },
      (synced) {
        _cachedItems = _cachedItems
            .map((i) => i.id == synced.id ? synced : i)
            .toList();
        emit(ChecklistLoaded(List.unmodifiable(_cachedItems)));
      },
    );
  }

  /// Ensures the given item has a valid UUID v4 as its ID.
  /// Returns a copy with a new UUID if the current ID is invalid.
  ChecklistItemModel _ensureValidUuid(ChecklistItemModel item) {
    final uuidRegex = RegExp(
      r'^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$',
      caseSensitive: false,
    );
    if (uuidRegex.hasMatch(item.id)) {
      return item;
    }
    // Invalid or non-UUID ID - generate a valid one
    developer.log('[ChecklistCubit] Replacing invalid ID with UUID v4',
        name: 'ChecklistCubit',
        error: {'originalId': item.id, 'newId': const Uuid().v4()});
    return item.copyWith(id: const Uuid().v4());
  }

  /// Delete checklist item (optimistic update)
  Future<void> deleteItem(String itemId) async {
    if (_currentDocumentId == null) {
      emit(const ChecklistError('No document loaded', code: 'no_document'));
      return;
    }

    final previousItems = List<ChecklistItemModel>.from(_cachedItems);

    _cachedItems = _cachedItems.where((i) => i.id != itemId).toList();
    emit(ChecklistLoaded(List.unmodifiable(_cachedItems)));

    final result = await _checklistRepository.deleteChecklistItem(
      _currentDocumentId!,
      itemId,
    );

    result.fold(
      (failure) {
        _cachedItems = previousItems;
        emit(ChecklistLoaded(
          List.unmodifiable(_cachedItems),
          errorMessage: failure.message,
        ));
      },
      (_) {
        // Successfully deleted on server
      },
    );
  }

  /// Save entire checklist (replaces all items)
  Future<void> saveChecklist(String documentId, List<ChecklistItemModel> items) async {
    _currentDocumentId = documentId;

    final previousItems = List<ChecklistItemModel>.from(_cachedItems);

    // Optimistic update
    _cachedItems = List.unmodifiable(items);
    emit(ChecklistLoaded(List.unmodifiable(_cachedItems)));

    final result = await _checklistRepository.saveChecklist(documentId, items);

    result.fold(
      (failure) {
        _cachedItems = previousItems;
        emit(ChecklistLoaded(
          List.unmodifiable(_cachedItems),
          errorMessage: failure.message,
        ));
      },
      (saved) {
        _cachedItems = List.unmodifiable(saved);
        emit(ChecklistLoaded(List.unmodifiable(_cachedItems)));
      },
    );
  }
}